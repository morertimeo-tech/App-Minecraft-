def agree(fr, base):
    """accord de « enchanté / usé » selon le premier mot du nom français."""
    w = fr.split()[0]
    if w in PLURAL: return base + 'es'
    if w in FEM: return base + 'e'
    return base

def fr_item(name):
    if name in FR: return FR[name]
    import re as _re
    m = _re.match(r'^Damaged (.+)$', name)
    if m:
        b = fr_item(m.group(1)); return f"{b} {agree(b, 'usé')}"
    m = _re.match(r'^Enchanted (.+) with Soul Speed$', name)
    if m:
        b = fr_item(m.group(1)); return f"{b} {agree(b, 'enchanté')} (Agilité des âmes)"
    m = _re.match(r'^Enchanted (.+)$', name)
    if m:
        b = fr_item(m.group(1)); return f"{b} {agree(b, 'enchanté')}"
    m = _re.match(r'^(.+) Pottery Sherd$', name)
    if m and m.group(1) in SHERD: return f"Tesson de poterie : {SHERD[m.group(1)]}"
    m = _re.match(r'^(.+) Armor Trim$', name)
    if m: return f"Modèle de forge : {m.group(1)}"
    m = _re.match(r'^(.+) Banner Pattern$', name)
    if m: return f"Motif de bannière : {m.group(1)}"
    m = _re.match(r'^Music Disc \((.+)\)$', name)
    if m: return f"Disque : {m.group(1)}"
    m = _re.match(r'^(.+) Camp Map$', name)
    if m and m.group(1) in CAMP: return f"Carte de camp ({CAMP[m.group(1)]})"
    m = _re.match(r'^(.+) Map$', name)
    if m:
        t = {'Buried Ancient City': 'cité antique enfouie', 'Buried Mineshaft': 'mine enfouie', 'Buried Treasure': 'trésor enterré',
             'Desert Pyramid': 'pyramide du désert', 'Jungle Pyramid': 'temple de la jungle', 'Warm Ocean Ruins': 'ruines océaniques chaudes'}.get(m.group(1))
        if t: return f"Carte ({t})"
    m = _re.match(r'^(Splash |Lingering )?Potion of (.+)$', name)
    if m and m.group(2) in EFFECT:
        e = EFFECT[m.group(2)]
        return {'Splash ': f"Potion de {e} (jetable)", 'Lingering ': f"Potion de {e} (persistante)", None: f"Potion de {e}"}[m.group(1)]
    m = _re.match(r'^Arrow of (.+)$', name)
    if m and m.group(1) in EFFECT: return f"Flèche de {EFFECT[m.group(1)]}"
    m = _re.match(r'^(.+) Stained Glass Pane$', name)
    if m and m.group(1) in COLOR: return f"Vitre teintée {COLOR[m.group(1)]}"
    return name   # non traduit : reste en anglais (listé par le script)

